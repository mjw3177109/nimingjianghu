import hashlib
import json
import sys
import tempfile
import unittest
from pathlib import Path
from unittest.mock import patch

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'tools'))
import character_frame_status as production


class FrameProvenanceTests(unittest.TestCase):
    def fixture(self, root):
        def save(path, value):
            file = root / path
            file.parent.mkdir(parents=True, exist_ok=True)
            file.write_text(json.dumps(value), encoding='utf-8')
        save('assets/characters/masters/production_manifest.json', {'tasks': [
            {'id': 'CHAR001', 'name': 'Shenyan', 'master_sha256': 'approved-master'}]})
        save('production/character_frames/CHAR001/frames_jobs.json', {'tasks': [
            {'id': 'CHAR001_down_idle', 'output_file': 'source.png'}]})
        (root / 'source.png').write_bytes(b'original generated bytes')
        receipt = {'approved': False, 'master_sha256': 'approved-master',
                   'sha256': hashlib.sha256((root / 'source.png').read_bytes()).hexdigest()}
        path = 'production/character_frames/CHAR001/receipts/CHAR001_down_idle.json'
        save(path, receipt)
        return root / path, receipt

    def test_modified_source_cannot_count_as_verified_generation(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            self.fixture(root)
            with patch.object(production, 'ROOT', root):
                self.assertEqual(production.snapshot()['generated'], 1)
                (root / 'source.png').write_bytes(b'replaced after import')
                with self.assertRaisesRegex(ValueError, 'changed after import'):
                    production.snapshot()

    def test_import_receipt_cannot_approve_frames(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            file, receipt = self.fixture(root)
            receipt['approved'] = True
            file.write_text(json.dumps(receipt), encoding='utf-8')
            with patch.object(production, 'ROOT', root):
                with self.assertRaisesRegex(ValueError, 'cannot approve'):
                    production.snapshot()


if __name__ == '__main__':
    unittest.main()
